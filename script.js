let currentLanguage = 'lv';
let cookiesAccepted = false;

function translatePage(lang) {
  currentLanguage = lang;
  document.documentElement.lang = lang;
  
  const elements = document.querySelectorAll('[data-translate]');
  elements.forEach(element => {
    const key = element.getAttribute('data-translate');
    if (translations[lang] && translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });
  
  const currentLangSpan = document.querySelector('.current-lang');
  if (currentLangSpan) {
    currentLangSpan.textContent = lang.toUpperCase();
  }
}

function toggleLanguageDropdown() {
  createOverlayDropdown();
}

function closeLanguageDropdown() {
  const existingOverlay = document.getElementById('lang-overlay');
  if (existingOverlay) {
    existingOverlay.remove();
  }
}

function createOverlayDropdown() {
  const button = document.getElementById('langDropdownBtn');
  const existingOverlay = document.getElementById('lang-overlay');
  
  if (existingOverlay) {
    existingOverlay.remove();
    return;
  }
  
  const overlay = document.createElement('div');
  overlay.id = 'lang-overlay';
  overlay.style.cssText = `
    position: fixed;
    top: 0;
    left: 0;
    width: 100vw;
    height: 100vh;
    background: rgba(0, 0, 0, 0.3);
    z-index: 2147483647;
    display: flex;
    align-items: flex-start;
    justify-content: flex-end;
    padding: 20px;
    cursor: pointer;
  `;
  
  const dropdownMenu = document.createElement('div');
  const buttonRect = button.getBoundingClientRect();
  const isMobile = window.innerWidth <= 768;
  
  if (isMobile) {
    dropdownMenu.style.cssText = `
      background: rgba(15, 42, 31, 0.98);
      backdrop-filter: blur(20px);
      border: 2px solid rgba(255, 255, 255, 0.3);
      border-radius: 8px;
      box-shadow: 0 12px 48px rgba(0, 0, 0, 0.5);
      min-width: 200px;
      position: absolute;
      top: 50%;
      left: 50%;
      transform: translate(-50%, -50%);
      cursor: default;
      opacity: 0;
      transition: all 0.3s ease;
    `;
  } else {
    dropdownMenu.style.cssText = `
      background: rgba(15, 42, 31, 0.98);
      backdrop-filter: blur(20px);
      border: 2px solid rgba(255, 255, 255, 0.3);
      border-radius: 8px;
      box-shadow: 0 12px 48px rgba(0, 0, 0, 0.5);
      min-width: 140px;
      margin-top: ${buttonRect.bottom + 8}px;
      margin-right: ${window.innerWidth - buttonRect.right}px;
      cursor: default;
      opacity: 0;
      transform: translateY(-10px);
      transition: all 0.3s ease;
    `;
  }
  
  const languages = [
    { code: 'lv', name: 'Latviešu' },
    { code: 'en', name: 'English' },
    { code: 'ru', name: 'Русский' }
  ];
  
  languages.forEach((lang, index) => {
    const option = document.createElement('button');
    
    option.style.cssText = `
      display: flex;
      align-items: center;
      justify-content: space-between;
      width: 100%;
      padding: 0.75rem 1rem;
      background: transparent;
      border: none;
      color: #ffffff;
      cursor: pointer;
      font-size: 0.9rem;
      text-align: left;
      font-family: inherit;
      transition: background 0.3s ease;
      ${index === 0 ? 'border-top-left-radius: 6px; border-top-right-radius: 6px;' : ''}
      ${index === languages.length - 1 ? 'border-bottom-left-radius: 6px; border-bottom-right-radius: 6px;' : ''}
    `;
    
    if (lang.code === currentLanguage) {
      option.style.background = 'rgba(255, 255, 255, 0.15)';
      option.classList.add('active');
    }
    
    option.innerHTML = `
      <span style="font-weight: 600; pointer-events: none;">${lang.code.toUpperCase()}</span>
      <span style="font-size: 0.8rem; opacity: 0.8; pointer-events: none;">${lang.name}</span>
    `;
    
    option.addEventListener('mouseenter', () => {
      option.style.background = 'rgba(255, 255, 255, 0.1)';
    });
    
    option.addEventListener('mouseleave', () => {
      if (lang.code === currentLanguage) {
        option.style.background = 'rgba(255, 255, 255, 0.15)';
      } else {
        option.style.background = 'transparent';
      }
    });
    
    const handleClick = (e) => {
      e.preventDefault();
      e.stopPropagation();
      translatePage(lang.code);
      overlay.remove();
    };
    
    ['click', 'mousedown', 'touchstart'].forEach(eventType => {
      option.addEventListener(eventType, handleClick, { passive: false });
    });
    
    option.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        translatePage(lang.code);
        overlay.remove();
      }
    });
    
    dropdownMenu.appendChild(option);
  });
  
  dropdownMenu.addEventListener('click', (e) => {
    e.stopPropagation();
  });
  
  overlay.addEventListener('click', () => {
    overlay.remove();
  });
  
  const handleEscape = (e) => {
    if (e.key === 'Escape') {
      overlay.remove();
      document.removeEventListener('keydown', handleEscape);
    }
  };
  document.addEventListener('keydown', handleEscape);
  
  overlay.appendChild(dropdownMenu);
  document.body.appendChild(overlay);
  
  requestAnimationFrame(() => {
    dropdownMenu.style.opacity = '1';
    if (isMobile) {
      dropdownMenu.style.transform = 'translate(-50%, -50%)';
    } else {
      dropdownMenu.style.transform = 'translateY(0)';
    }
  });
}

function showCookieBanner() {
  const banner = document.getElementById('cookie-banner');
  if (!cookiesAccepted) {
    banner.classList.add('show');
  }
}

function hideCookieBanner() {
  const banner = document.getElementById('cookie-banner');
  banner.classList.remove('show');
}

function showMapConsentModal() {
  const modal = document.getElementById('map-consent-modal');
  modal.classList.add('show');
  
  // Focus trap
  const focusableElements = modal.querySelectorAll('button');
  const firstElement = focusableElements[0];
  const lastElement = focusableElements[focusableElements.length - 1];
  
  firstElement.focus();
  
  modal.addEventListener('keydown', (e) => {
    if (e.key === 'Tab') {
      if (e.shiftKey) {
        if (document.activeElement === firstElement) {
          e.preventDefault();
          lastElement.focus();
        }
      } else {
        if (document.activeElement === lastElement) {
          e.preventDefault();
          firstElement.focus();
        }
      }
    }
  });
}

function hideMapConsentModal() {
  const modal = document.getElementById('map-consent-modal');
  modal.classList.remove('show');
}

